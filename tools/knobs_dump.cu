// Export the knob registry (runtime/knobs.h) for tools and docs.
//   tools/knobs_dump --json  > tools/autotune/profiles/knobs.json   (autotune search-space source)
//   tools/knobs_dump --md    > docs/knobs-table.md                  (generated part of docs/knobs.md)
//   tools/knobs_dump --effective                                     (validate env/recipe, print the KNOBS line)
// JSON keeps the registry fields verbatim and adds "choices" for enums, so a harness can build an
// Optuna categorical/int distribution per tunable or numeric knob without parsing range strings.
#include "runtime/knobs.h"
#include <cstdio>
#include <cstring>
#include <string>

static std::string q(const char *s) { std::string o; knob_detail::json_str(o, s); return o; }

static void dump_json() {
    printf("{\n  \"schema\": \"dgx-knobs/v1\",\n  \"source\": \"runtime/knobs.h\",\n  \"prefixes\": [");
    bool first = true;
    for (const char *p : g_knob_prefixes) { printf("%s%s", first ? "" : ", ", q(p).c_str()); first = false; }
    printf("],\n  \"knobs\": [\n");
    size_t n = sizeof(g_knobs) / sizeof(g_knobs[0]);
    for (size_t i = 0; i < n; i++) {
        const KnobDef &k = g_knobs[i];
        printf("    {\"name\": %s, \"type\": %s, \"default\": %s, \"range\": %s, \"class\": %s,\n",
               q(k.name).c_str(), q(knob_detail::type_name(k.type)).c_str(), q(k.dflt).c_str(), q(k.range).c_str(),
               q(knob_detail::class_name(k.cls)).c_str());
        printf("     \"scope\": %s, \"gates\": %s, \"desc\": %s", q(k.scope).c_str(), q(k.gates).c_str(), q(k.desc).c_str());
        if (k.type == KNOB_ENUM) {
            printf(",\n     \"choices\": [");
            std::string r(k.range); size_t p = 0; bool f = true;
            while (p <= r.size()) { size_t e = r.find('|', p); if (e == std::string::npos) e = r.size();
                printf("%s%s", f ? "" : ", ", q(r.substr(p, e - p).c_str()).c_str()); f = false; p = e + 1; }
            printf("]");
        }
        printf("}%s\n", i + 1 < n ? "," : "");
    }
    printf("  ]\n}\n");
}

static void md_cell(const char *s) { for (; *s; s++) { if (*s == '|') printf("\\|"); else putchar(*s); } }

static void dump_md() {
    printf("<!-- generated by tools/knobs_dump --md from runtime/knobs.h; do not edit by hand -->\n\n");
    for (KnobClass c : {KNOB_TUNABLE, KNOB_NUMERIC, KNOB_FIXED, KNOB_DIAGNOSTIC}) {
        printf("### %s\n\n| knob | type | default | range | scope | gates to re-run | description |\n|---|---|---|---|---|---|---|\n",
               knob_detail::class_name(c));
        for (const KnobDef &k : g_knobs) {
            if (k.cls != c) continue;
            printf("| `%s` | %s | ", k.name, knob_detail::type_name(k.type));
            if (*k.dflt) { printf("`"); md_cell(k.dflt); printf("`"); } else printf("(unset)");
            printf(" | `"); md_cell(k.range); printf("` | "); md_cell(k.scope); printf(" | "); md_cell(k.gates);
            printf(" | "); md_cell(k.desc); printf(" |\n");
        }
        printf("\n");
    }
}

int main(int argc, char **argv) {
    if (argc == 2 && !strcmp(argv[1], "--json")) dump_json();
    else if (argc == 2 && !strcmp(argv[1], "--md")) dump_md();
    else if (argc == 2 && !strcmp(argv[1], "--effective")) knobs_init("knobs_dump");
    else { fprintf(stderr, "usage: %s --json | --md | --effective\n", argv[0]); return 1; }
    return 0;
}
